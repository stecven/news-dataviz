def main():
    con = sqlite3.connect(DB)
    pid = con.execute("SELECT id FROM pages ORDER BY id DESC LIMIT 1").fetchone()[0]
    con.execute("DELETE FROM chart_points WHERE page_id=?", (pid,))
    n = 0
    for key, title, pts in DATA:
        for i, (label, val, unit) in enumerate(pts, 1):
            con.execute("INSERT INTO chart_points(page_id,chart_key,chart_title,seq,label,value,unit) "
                        "VALUES(?,?,?,?,?,?,?)", (pid, key, title, i, label, val, unit))
            n += 1
    con.commit()
    print(f"写入 {n} 个数据点，page_id={pid}")
    for key, title, pts in DATA:
        print(f"  {key}: {title} ({len(pts)}点)")
    con.close()


if __name__ == "__main__":
    main()
